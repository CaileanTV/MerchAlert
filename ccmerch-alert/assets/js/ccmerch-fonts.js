/**
 * CCMerch Alert — Shared Google Fonts system.
 *
 * Exports window.CCMerchFonts = { FontPreview, FontSelector }
 *
 * FontPreview  — Lazy-loads Google Fonts CSS via IntersectionObserver.
 *                Only fonts visible (or about to be visible) in the
 *                viewport ever receive a <link> request.
 *
 * FontSelector — Custom accessible dropdown for the Layout Editor
 *                properties panel.  Replaces the plain <select> so each
 *                option can display a live font preview swatch.
 *                Integrates with layout-editor.js via a hidden
 *                [data-appearance] input that dispatches a real 'change'
 *                event when the user picks a font.
 *
 * Must be loaded BEFORE layout-editor.js on every page that uses the
 * Layout Editor (admin Overlay page, Creator Portal).
 */

/* global window, document, IntersectionObserver */

window.CCMerchFonts = ( function () {
	'use strict';

	/* =========================================================================
	   FontPreview
	   Injects a Google Fonts CSS2 <link> for a given family, but only once,
	   and only when the element that needs it scrolls into the viewport.
	   ======================================================================= */

	var FontPreview = ( function () {

		/** Tracks which CSS URLs have already been injected. */
		var _loaded = {};

		/** Shared IntersectionObserver for all observed elements. */
		var _observer = null;

		/**
		 * Builds a minimal Google Fonts CSS2 URL loading only weight 400
		 * (sufficient for preview text).
		 *
		 * @param  {string} family  Google Fonts family name.
		 * @return {string}         URL, or '' when family is empty / inherit.
		 */
		function buildUrl( family ) {
			if ( ! family || 'inherit' === family ) {
				return '';
			}
			return 'https://fonts.googleapis.com/css2?family='
				+ encodeURIComponent( family )
				+ ':wght@400&display=swap';
		}

		/**
		 * Injects the Google Fonts <link> for a family immediately.
		 * Safe to call multiple times — duplicate requests are suppressed.
		 *
		 * @param  {string} family  Google Fonts family name.
		 * @return {void}
		 */
		function loadFamily( family ) {
			var url = buildUrl( family );
			if ( ! url || _loaded[ url ] ) {
				return;
			}
			_loaded[ url ] = true;
			var link = document.createElement( 'link' );
			link.rel         = 'stylesheet';
			link.crossOrigin = 'anonymous';
			link.href        = url;
			document.head.appendChild( link );
		}

		/**
		 * Schedules a font load for when `element` becomes visible.
		 *
		 * Stores the family name as `data-preview-font` on the element so
		 * the shared IntersectionObserver callback can read it without a
		 * closure per element.
		 *
		 * Falls back to an immediate loadFamily() call when
		 * IntersectionObserver is unavailable.
		 *
		 * @param  {Element} element  DOM node to observe.
		 * @param  {string}  family   Google Fonts family name.
		 * @return {void}
		 */
		function observe( element, family ) {
			if ( ! family || 'inherit' === family || ! element ) {
				return;
			}

			if ( typeof IntersectionObserver === 'undefined' ) {
				loadFamily( family );
				return;
			}

			if ( ! _observer ) {
				_observer = new IntersectionObserver(
					function ( entries ) {
						entries.forEach( function ( entry ) {
							if ( ! entry.isIntersecting ) {
								return;
							}
							loadFamily( entry.target.dataset.previewFont );
							_observer.unobserve( entry.target );
						} );
					},
					{ rootMargin: '150px 0px' }
				);
			}

			element.dataset.previewFont = family;
			_observer.observe( element );
		}

		/**
		 * Automatically observes every [data-font-preview] element present in
		 * the document at load time.  Called on DOMContentLoaded so admin
		 * table rows gain previews without per-page JS.
		 *
		 * @return {void}
		 */
		function observeAll() {
			document.querySelectorAll( '[data-font-preview]' ).forEach( function ( el ) {
				observe( el, el.getAttribute( 'data-font-preview' ) );
			} );
		}

		return {
			buildUrl:   buildUrl,
			loadFamily: loadFamily,
			observe:    observe,
			observeAll: observeAll,
		};

	} )();

	/* =========================================================================
	   FontSelector
	   Custom dropdown widget for the Layout Editor properties panel.

	   HTML contract (generated by fontSelectInput() in layout-editor.js):

	     <div class="ccmerch-fs" data-font-selector>
	       <div class="ccmerch-fs__trigger" tabindex="0" role="button"
	            aria-haspopup="listbox" aria-expanded="false">
	         <span class="ccmerch-fs__trigger-swatch">Aa</span>
	         <span class="ccmerch-fs__trigger-label">Poppins</span>
	         <span class="ccmerch-fs__trigger-arrow">▾</span>
	       </div>
	       <div class="ccmerch-fs__panel" hidden>
	         <input type="search" class="ccmerch-fs__search" placeholder="Search fonts…">
	         <div class="ccmerch-fs__list" role="listbox"></div>
	       </div>
	       <input type="hidden" data-appearance="font_family" value="Poppins">
	     </div>

	   When initAll(container) is called, each widget with [data-font-selector]
	   inside `container` is wired up:
	   - Options list is built from window.ccmerchApprovedFonts
	     (supports both string[] and {family,category}[] formats).
	   - IntersectionObserver lazy-loads the Google Font for each option
	     as it scrolls into the visible area of the list panel.
	   - Selecting an option updates the hidden input value and dispatches
	     a native 'change' event so layout-editor.js's bindAppearanceInputs()
	     handler fires automatically — no coupling between the two scripts.
	   ======================================================================= */

	var FontSelector = ( function () {

		/** HTML-escape helper. */
		function esc( s ) {
			return String( s )
				.replace( /&/g, '&amp;' )
				.replace( /</g, '&lt;' )
				.replace( />/g, '&gt;' )
				.replace( /"/g, '&quot;' );
		}

		/**
		 * Returns the approved fonts array, normalised to {family, category}[]
		 * regardless of whether the global is string[] or object[].
		 *
		 * @return {Array<{family:string,category:string}>}
		 */
		function getFonts() {
			var raw = window.ccmerchApprovedFonts;
			if ( ! Array.isArray( raw ) ) {
				return [];
			}
			return raw.map( function ( item ) {
				return 'string' === typeof item
					? { family: item, category: '' }
					: { family: item.family || '', category: item.category || '' };
			} );
		}

		/**
		 * Builds the options list HTML for the scrollable panel.
		 *
		 * Each option includes a live-preview swatch span whose font-family
		 * is set inline so the IntersectionObserver can load the correct CSS.
		 *
		 * @param  {Array}  fonts       Normalised font array.
		 * @param  {string} currentVal  Currently selected family, or 'inherit'.
		 * @return {string}             HTML string for list innerHTML.
		 */
		function buildOptions( fonts, currentVal ) {
			var html = '';

			// Default / system font option.
			var defSel = ( ! currentVal || 'inherit' === currentVal )
				? ' ccmerch-fs__option--selected'
				: '';
			html += '<div class="ccmerch-fs__option' + defSel + '" data-value="inherit" role="option">';
			html += '<span class="ccmerch-fs__option-swatch ccmerch-fs__option-swatch--default">Aa</span>';
			html += '<span class="ccmerch-fs__option-label">&#8212; Default (system font) &#8212;</span>';
			html += '</div>';

			fonts.forEach( function ( f ) {
				if ( ! f.family ) { return; }
				var sel = ( f.family === currentVal ) ? ' ccmerch-fs__option--selected' : '';
				html += '<div class="ccmerch-fs__option' + sel + '"'
					+ ' data-value="' + esc( f.family ) + '"'
					+ ' data-preview-font="' + esc( f.family ) + '"'
					+ ' role="option">';
				// Swatch: font is loaded lazily via IntersectionObserver.
				html += '<span class="ccmerch-fs__option-swatch"'
					+ ' style="font-family:\'' + esc( f.family ) + '\',sans-serif">Aa</span>';
				html += '<span class="ccmerch-fs__option-label">' + esc( f.family ) + '</span>';
				if ( f.category ) {
					html += '<span class="ccmerch-fs__option-cat">' + esc( f.category ) + '</span>';
				}
				html += '</div>';
			} );

			return html;
		}

		/**
		 * Updates the trigger button to reflect the given selection.
		 *
		 * @param  {Element} trigLabel   The label span inside the trigger.
		 * @param  {Element} trigSwatch  The swatch span inside the trigger.
		 * @param  {string}  val         Selected family name, or 'inherit'.
		 * @return {void}
		 */
		function updateTrigger( trigLabel, trigSwatch, val ) {
			if ( trigLabel ) {
				trigLabel.textContent = ( ! val || 'inherit' === val )
					? '— Default —'
					: val;
			}

			if ( trigSwatch ) {
				if ( val && 'inherit' !== val ) {
					trigSwatch.style.fontFamily = '\'' + val + '\',sans-serif';
					trigSwatch.style.display    = '';
					// Load the font so the trigger swatch renders correctly.
					FontPreview.loadFamily( val );
				} else {
					trigSwatch.style.display = 'none';
				}
			}
		}

		/**
		 * Registers IntersectionObserver on every option swatch inside the list.
		 *
		 * Must be called after the list innerHTML has been set and the panel
		 * DOM is attached.
		 *
		 * @param  {Element} list  The .ccmerch-fs__list container element.
		 * @return {void}
		 */
		function observeListItems( list ) {
			list.querySelectorAll( '.ccmerch-fs__option[data-preview-font]' ).forEach( function ( opt ) {
				FontPreview.observe( opt, opt.dataset.previewFont );
			} );
		}

		/**
		 * Wires up a single FontSelector widget.
		 *
		 * @param  {Element} container  The root [data-font-selector] element.
		 * @return {void}
		 */
		function initOne( container ) {
			var hidden     = container.querySelector( '[data-appearance]' );
			var trigger    = container.querySelector( '.ccmerch-fs__trigger' );
			var search     = container.querySelector( '.ccmerch-fs__search' );
			var list       = container.querySelector( '.ccmerch-fs__list' );
			var panel      = container.querySelector( '.ccmerch-fs__panel' );
			var trigLabel  = container.querySelector( '.ccmerch-fs__trigger-label' );
			var trigSwatch = container.querySelector( '.ccmerch-fs__trigger-swatch' );

			if ( ! hidden || ! trigger || ! list || ! panel ) {
				return;
			}

			var fonts      = getFonts();
			var currentVal = hidden.value || 'inherit';

			// Populate options.
			list.innerHTML = buildOptions( fonts, currentVal );
			observeListItems( list );
			updateTrigger( trigLabel, trigSwatch, currentVal );

			// ── Open / close panel ────────────────────────────────────────────

			trigger.addEventListener( 'click', function () {
				var isOpen = ! panel.hidden;
				if ( isOpen ) {
					panel.hidden = true;
					trigger.setAttribute( 'aria-expanded', 'false' );
				} else {
					panel.hidden = false;
					trigger.setAttribute( 'aria-expanded', 'true' );
					if ( search ) { search.focus(); }
					// Scroll selected option into view.
					var selected = list.querySelector( '.ccmerch-fs__option--selected' );
					if ( selected ) { selected.scrollIntoView( { block: 'nearest' } ); }
				}
			} );

			// Close when clicking outside the widget.
			document.addEventListener( 'click', function ( e ) {
				if ( ! container.contains( e.target ) ) {
					panel.hidden = true;
					trigger.setAttribute( 'aria-expanded', 'false' );
				}
			} );

			// Keyboard: Escape closes.
			container.addEventListener( 'keydown', function ( e ) {
				if ( 'Escape' === e.key ) {
					panel.hidden = true;
					trigger.setAttribute( 'aria-expanded', 'false' );
					trigger.focus();
				}
			} );

			// ── Search ────────────────────────────────────────────────────────

			if ( search ) {
				search.addEventListener( 'input', function () {
					var q = search.value.toLowerCase().trim();
					list.querySelectorAll( '.ccmerch-fs__option' ).forEach( function ( opt ) {
						var val    = ( opt.dataset.value || '' ).toLowerCase();
						var isDefault = ( 'inherit' === opt.dataset.value );
						opt.hidden = !! q && ! isDefault && val.indexOf( q ) === -1;
					} );
				} );
			}

			// ── Option selection ──────────────────────────────────────────────

			list.addEventListener( 'click', function ( e ) {
				var opt = e.target.closest( '.ccmerch-fs__option' );
				if ( ! opt ) { return; }

				var val = opt.dataset.value || 'inherit';

				// Update the hidden input — this is what layout-editor.js reads.
				hidden.value = val;

				// Dispatch a native 'change' event so bindAppearanceInputs()
				// in layout-editor.js fires and calls applyAppearanceProp().
				hidden.dispatchEvent( new Event( 'change', { bubbles: true } ) );

				// Update trigger appearance.
				updateTrigger( trigLabel, trigSwatch, val );

				// Update selected highlight.
				list.querySelectorAll( '.ccmerch-fs__option' ).forEach( function ( o ) {
					o.classList.toggle( 'ccmerch-fs__option--selected', o === opt );
				} );

				// Load the selected font immediately (not lazy).
				if ( 'inherit' !== val ) {
					FontPreview.loadFamily( val );
				}

				// Close panel.
				panel.hidden = true;
				trigger.setAttribute( 'aria-expanded', 'false' );
			} );
		}

		/**
		 * Initialises all FontSelector widgets within `container`.
		 *
		 * Called by layout-editor.js immediately after renderProps() rebuilds
		 * the properties panel innerHTML.
		 *
		 * @param  {Element|null} container  Parent element to search within.
		 *                                   Defaults to document when null.
		 * @return {void}
		 */
		function initAll( container ) {
			( container || document ).querySelectorAll( '[data-font-selector]' ).forEach( initOne );
		}

		return { initAll: initAll };

	} )();

	/* =========================================================================
	   Auto-observe admin table previews on DOMContentLoaded.
	   The admin Font Library PHP table renders <span data-font-preview="Family">
	   cells.  This single call wires up lazy loading for all of them without
	   any per-page JS.
	   ======================================================================= */

	if ( document.readyState === 'loading' ) {
		document.addEventListener( 'DOMContentLoaded', FontPreview.observeAll );
	} else {
		FontPreview.observeAll();
	}

	/* =========================================================================
	   Public API
	   ======================================================================= */

	return {
		FontPreview:  FontPreview,
		FontSelector: FontSelector,
	};

} )();
