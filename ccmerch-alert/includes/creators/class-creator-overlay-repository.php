/**
 * All SQL operations for the ccmerch_creator_overlay_settings table.
 *
 * One row per creator. Each row stores:
 *  - creator_id  — FK to ccmerch_creator_profiles.id (UNIQUE)
 *  - overlay_id  — 32-char hex access token for the browser-source URL (UNIQUE)
 *  - settings    — JSON blob using the same field keys as ccmerch_overlay_settings
 *
 * Must never: contain business rules or rendering logic.
 * Must never: be called directly from admin rendering classes.
 */
final class Creator_Overlay_Repository {

	/** @var string Table name including $wpdb prefix. */
	private string $table;

	public function __construct() {
		global $wpdb;
		$this->table = $wpdb->prefix . 'ccmerch_creator_overlay_settings';
	}

	// -------------------------------------------------------------------------
	// Read API
	// -------------------------------------------------------------------------

	/**
	 * Returns the raw settings row for a creator, or null when none exists.
	 *
	 * @param  int $creator_id Creator profile primary key.
	 * @return array<string, mixed>|null
	 */
	public function find_by_creator_id( int $creator_id ): ?array {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$row = $wpdb->get_row(
			$wpdb->prepare( "SELECT * FROM {$this->table} WHERE creator_id = %d LIMIT 1", $creator_id ),
			ARRAY_A
		);

		return \is_array( $row ) ? $row : null;
	}

	/**
	 * Returns the Unix timestamp of updated_at for the given overlay ID.
	 *
	 * Reads directly from the database, bypassing all caches, so it is safe to
	 * call in a long-running SSE loop where in-process caches are stale.
	 *
	 * @param  string $overlay_id 32-char hex overlay access token.
	 * @return int Unix timestamp, or 0 when not found.
	 */
	public function get_updated_at_by_overlay_id( string $overlay_id ): int {
		global $wpdb;
		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$value = $wpdb->get_var(
			$wpdb->prepare(
				"SELECT UNIX_TIMESTAMP(updated_at) FROM {$this->table} WHERE overlay_id = %s LIMIT 1",
				$overlay_id
			)
		);
		return null !== $value ? (int) $value : 0;
	}

	/**
	 * Returns the creator_id for the given overlay ID, or null when not found.
	 *
	 * Used by Creator_Overlay_Controller to route browser-source requests.
	 *
	 * @param  string $overlay_id 32-char hex overlay access token.
	 * @return int|null Creator profile primary key, or null.
	 */
	public function find_creator_id_by_overlay_id( string $overlay_id ): ?int {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$creator_id = $wpdb->get_var(
			$wpdb->prepare( "SELECT creator_id FROM {$this->table} WHERE overlay_id = %s LIMIT 1", $overlay_id )
		);

		return null !== $creator_id ? (int) $creator_id : null;
	}

	// -------------------------------------------------------------------------
	// Write API
	// -------------------------------------------------------------------------

	/**
	 * Creates a new overlay settings row for a creator.
	 *
	 * Called automatically when a Creator Profile is created. The overlay_id
	 * is generated by the caller (Creator_Service) before this method runs.
	 * Default settings are stored as a JSON blob of Overlay_Settings defaults.
	 *
	 * @param  int    $creator_id Creator profile primary key.
	 * @param  string $overlay_id 32-char hex overlay access token.
	 * @return bool True on success.
	 */
	public function create( int $creator_id, string $overlay_id ): bool {
		global $wpdb;

		$defaults = $this->default_settings();
		$now      = \gmdate( 'Y-m-d H:i:s' );

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$result = $wpdb->insert(
			$this->table,
			[
				'creator_id' => $creator_id,
				'overlay_id' => $overlay_id,
				'settings'   => (string) wp_json_encode( $defaults ),
				'created_at' => $now,
				'updated_at' => $now,
			],
			[ '%d', '%s', '%s', '%s', '%s' ]
		);

		return false !== $result;
	}

	/**
	 * Replaces the settings blob for an existing creator overlay row.
	 *
	 * Does not validate or sanitize data — caller is responsible.
	 *
	 * @param  int                  $creator_id Creator profile primary key.
	 * @param  array<string, mixed> $settings   Sanitized settings array.
	 * @return bool True on success.
	 */
	public function save_settings( int $creator_id, array $settings ): bool {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$result = $wpdb->update(
			$this->table,
			[
				'settings'   => (string) wp_json_encode( $settings ),
				'updated_at' => \gmdate( 'Y-m-d H:i:s' ),
			],
			[ 'creator_id' => $creator_id ],
			[ '%s', '%s' ],
			[ '%d' ]
		);

		return false !== $result;
	}

	/**
	 * Replaces the overlay_id for an existing creator overlay row.
	 *
	 * Called when a creator generates a new browser-source URL. The old URL
	 * is immediately invalidated because the old overlay_id no longer exists.
	 *
	 * @param  int    $creator_id Creator profile primary key.
	 * @param  string $overlay_id New 32-char hex overlay access token.
	 * @return bool True on success.
	 */
	public function update_overlay_id( int $creator_id, string $overlay_id ): bool {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$result = $wpdb->update(
			$this->table,
			[
				'overlay_id' => $overlay_id,
				'updated_at' => \gmdate( 'Y-m-d H:i:s' ),
			],
			[ 'creator_id' => $creator_id ],
			[ '%s', '%s' ],
			[ '%d' ]
		);

		return false !== $result;
	}

	/**
	 * Deletes the overlay settings row for a creator.
	 *
	 * Called when a Creator Profile is deleted, so no orphaned rows remain.
	 *
	 * @param  int $creator_id Creator profile primary key.
	 * @return bool True on success.
	 */
	public function delete_by_creator_id( int $creator_id ): bool {
		global $wpdb;

		// phpcs:ignore WordPress.DB.DirectDatabaseQuery
		$result = $wpdb->delete( $this->table, [ 'creator_id' => $creator_id ], [ '%d' ] );

		return false !== $result;
	}

	// -------------------------------------------------------------------------
	// Private helpers
	// -------------------------------------------------------------------------

	/**
	 * Returns the default settings for a new creator overlay profile.
	 *
	 * Uses the same field keys and defaults as Overlay_Settings so the
